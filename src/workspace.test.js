test('Telegram intake deduplicates and approval creates one assigned query', (t) => {
  const { store, founder, designer, projectId } = fixture(t);
  const input = { TelegramProjectID: 'P001', GroupChatID: '-123', RequestID: 'REQ-1', RequestType: 'Question', OriginalMessage: 'Can we use a lighter shade?', OriginalSenderName: 'Maya', OriginalSenderTelegramID: '42', SourceMessageID: '7', AttachmentsJSON: '[{"type":"Photo","fileId":"large"}]' };
  store.telegramRequest(input); store.telegramRequest(input);
  assert.equal(store.snapshot(founder).requests.length, 1);
  assert.equal(JSON.parse(store.snapshot(founder).requests[0].sourceMetadata).originalSenderTelegramId, '42');
  assert.equal(store.snapshot(designer).requests.length, 0);
  const count = store.snapshot(designer).tasks.length;
  assert.throws(() => store.reviewRequest(designer, 'REQ-1', { status: 'Approved', ownerId: designer.id, title: 'Colour review' }), /founder/);
  const result = store.reviewRequest(founder, 'REQ-1', { status: 'Approved', ownerId: designer.id, title: 'Colour review' });
  assert.equal(store.snapshot(designer).tasks.length, count + 1);
  assert.equal(store.thread(designer, result.taskId).task.kind, 'Query');
  assert.equal(store.thread(designer, result.taskId).requests[0].body, input.OriginalMessage);
  assert.equal(store.thread(designer, result.taskId).requests[0].attachments[0].fileId, 'large');
  assert.equal(store.reviewRequest(founder, 'REQ-1', { status: 'Approved', ownerId: designer.id, title: 'Another title' }).taskId, result.taskId);
  assert.equal(store.snapshot(designer).tasks.length, count + 1);
  assert.ok(store.snapshot(designer).notifications.some((n) => n.kind === 'Assignment' && n.taskId === result.taskId));
  assert.throws(() => store.telegramRequest({ ...input, GroupChatID: '-wrong' }), /Link this bot project/);
  assert.equal(store.snapshot(founder).projects.find((p) => p.id === projectId).status, 'Active');
});
