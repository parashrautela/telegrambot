test('messages, sessions, and read positions survive a database restart', (t) => {
  const directory = mkdtempSync(join(tmpdir(), 'iksha-workspace-'));
  const filename = join(directory, 'workspace.sqlite');
  const { store, founder, designer, taskId, token } = fixture(t, filename);
  const { seq } = store.postMessage(founder, taskId, { body: 'Persistent message' });
  store.readThread(designer, taskId, seq);
  store.close();
  const reopened = new WorkspaceStore(filename);
  t.after(() => { reopened.close(); rmSync(directory, { recursive: true, force: true }); });
  assert.equal(reopened.authenticate(token).id, designer.id);
  assert.equal(reopened.thread(designer, taskId).messages[0].body, 'Persistent message');
  assert.equal(reopened.snapshot(designer).tasks.find((task) => task.id === taskId).unread, 0);
});
test('HTTP API enforces sessions, origin, membership, and integration authentication', async (t) => {
  const { store, taskId } = fixture(t);
  const server = createWorkspaceServer({ store, origin: 'http://workspace.test', integrationSecret: 'test-integration-secret' });
  await new Promise((resolve, reject) => { server.once('error', reject); server.listen(0, '127.0.0.1', resolve); });
  t.after(async () => { await new Promise((resolve) => server.close(resolve)); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = (path, { method = 'GET', input, cookie, origin, secret } = {}) => fetch(base + path, { method, headers: { ...(input ? { 'content-type': 'application/json' } : {}), ...(cookie ? { cookie } : {}), ...(origin ? { origin } : {}), ...(secret ? { authorization: `Bearer ${secret}` } : {}) }, ...(input ? { body: JSON.stringify(input) } : {}) });
  assert.equal((await request('/api/workspace')).status, 401);
  assert.equal((await request('/api/workspace/login', { method: 'POST', input: { id: 'founder', password }, origin: 'https://evil.example' })).status, 403);
  const login = await request('/api/workspace/login', { method: 'POST', input: { id: 'other', password }, origin: 'http://workspace.test' });
  const cookie = login.headers.get('set-cookie').split(';')[0];
  assert.match(login.headers.get('set-cookie'), /HttpOnly; SameSite=Strict/);
  assert.equal((await request(`/api/workspace/tasks/${taskId}`, { cookie })).status, 404);
  assert.equal((await request('/api/workspace/users', { method: 'POST', cookie, input: { id: 'hack' } })).status, 403);
  const payload = { TelegramProjectID: 'P001', GroupChatID: '-123', RequestID: 'HTTP-REQ', RequestType: 'Question', OriginalMessage: 'Where should the light go?', OriginalSenderName: 'Maya' };
  assert.equal((await request('/api/integrations/telegram/requests', { method: 'POST', input: payload })).status, 401);
  assert.equal((await request('/api/integrations/telegram/requests', { method: 'POST', input: payload, secret: 'test-integration-secret' })).status, 200);
  assert.equal(store.get('SELECT COUNT(*) AS count FROM requests').count, 1);
  assert.equal((await request('/api/workspace/logout', { method: 'POST', cookie, input: {} })).status, 200);
  assert.equal((await request('/api/workspace', { cookie })).status, 401);
});
