test('thread reads are independent, monotonic, and exclude own messages', (t) => {
  const { store, founder, designer, projectId, taskId } = fixture(t);
  const second = store.createTask(founder, projectId, { title: 'Another room', kind: 'Task', ownerId: designer.id }).id;
  const firstSeq = store.postMessage(founder, taskId, { body: 'Review this room' }).seq;
  const secondSeq = store.postMessage(founder, second, { body: 'Another update' }).seq;
  store.postMessage(designer, taskId, { body: 'I will review it' });
  let snapshot = store.snapshot(designer);
  assert.equal(snapshot.tasks.find((task) => task.id === taskId).unread, 1);
  assert.equal(snapshot.projects[0].unread, 2);
  store.readThread(designer, taskId, firstSeq);
  snapshot = store.snapshot(designer);
  assert.equal(snapshot.tasks.find((task) => task.id === taskId).unread, 0);
  assert.equal(snapshot.tasks.find((task) => task.id === second).unread, 1);
  assert.ok(store.snapshot(designer).notifications.find((n) => n.messageSeq === firstSeq).readAt);
  assert.equal(store.snapshot(designer).notifications.find((n) => n.messageSeq === secondSeq).readAt, null);
  assert.equal(store.snapshot(founder).tasks.find((task) => task.id === taskId).unread, 1);
  store.readThread(designer, taskId, 0);
  assert.equal(store.snapshot(designer).tasks.find((task) => task.id === taskId).unread, 0);
  assert.throws(() => store.readThread(designer, taskId, secondSeq), /belong to this thread/);
  assert.throws(() => store.readThread(designer, taskId, 999999), /belong to this thread/);
});
test('project revocation blocks direct reads, writes, and notifications but preserves other projects', (t) => {
  const { store, founder, designer, other, client, projectId, taskId, token } = fixture(t);
  assert.throws(() => store.thread(other, taskId), /access revoked/);
  assert.equal(store.snapshot(other).projects.length, 0);
  const second = store.createProject(founder, { name: 'Second project', clientId: client.id }).id;
  store.setMember(founder, second, designer.id, true);
  store.postMessage(founder, taskId, { body: 'Private update' });
  const notification = store.snapshot(designer).notifications.at(-1);
  store.setMember(founder, projectId, designer.id, false);
  assert.equal(store.authenticate(token).id, designer.id);
  assert.throws(() => store.thread(designer, taskId), /access revoked/);
  assert.throws(() => store.postMessage(designer, taskId, { body: 'No access' }), /access revoked/);
  assert.throws(() => store.readThread(designer, taskId, 0), /access revoked/);
  assert.throws(() => store.readNotification(designer, notification.id), /not found/);
  assert.deepEqual(store.snapshot(designer).projects.map((p) => p.id), [second]);
  assert.equal(store.thread(founder, taskId).messages.length, 1);
  assert.equal(store.thread(founder, taskId).task.ownerId, null);
});
