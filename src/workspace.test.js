  store.createUser(founder, { id: 'other', name: 'Aarav Mehta', role: 'Employee', password });
  const designerLogin = store.login('designer', password);
  const other = store.login('other', password).user;
  const client = store.createClient(founder, { name: 'Maya Sharma' });
  const project = store.createProject(founder, { name: 'Parash ka Ghar', clientId: client.id, telegramProjectId: 'P001', groupChatId: '-123' });
